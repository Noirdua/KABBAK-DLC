#!/usr/bin/env python3
"""Build plugins/liber-777/data/liber-777.json + data/liber-777.js from open_777.

Source: https://github.com/adamblvck/open_777 (src/constants/liber_777.js, MIT)
        transcription of Liber 777 (1909, Aleister Crowley, public domain).

Usage:
    python3 data/build-liber-777.py <path-to>/liber_777.js

Writes two copies of the same payload:
  data/liber-777.json  — for tooling / inspection
  data/liber-777.js    — <script>-loadable copy the page prefers, so it needs
                         no API route and no plugin-asset fetch at all.
"""
import json
import re
import sys
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PLACEHOLDERS = {"", "...", "…", "-", "—", "\u2026"}
NUMERAL_RE = re.compile(r"^([IVXLC]+(?:\.[IVXLC]+)?)\.\s*(.+)$", re.S)
COMPANION_RE = re.compile(r"^(II|VI|VII|CXVIII|CXXXVII)\.", re.I)

# Headings that are just a parent row repeated in another script/translation.
# Kept in the data; the page shows them as sub-lines of their parent row.
TRANSLITERATION_RE = re.compile(
    r"(Transliterat|Translation of|English of|Meaning\b|English\b|\.1$|Brief)", re.I)


def split_index(text):
    text = re.sub(r"\s+", " ", str(text or "").replace("\r\n", " ").replace("\n", " ")).strip()
    m = NUMERAL_RE.match(text)
    return (m.group(1), m.group(2).strip()) if m else ("", text)


def clean(value):
    if value is None:
        return ""
    text = str(value).replace("\r\n", "\n").replace("\r", "\n")
    text = "\n".join(line.strip() for line in text.split("\n"))
    text = re.sub(r"\n{2,}", "\n", text).strip()
    if re.fullmatch(r"-?\d+\.0+", text):
        text = text.split(".")[0]
    if text in PLACEHOLDERS or text.lower() == "none":
        return ""
    return text


def main():
    src_path = sys.argv[1] if len(sys.argv) > 1 else "liber_777.js"
    raw = open(src_path, encoding="utf-8").read()
    raw = raw[raw.index("["):].rstrip().rstrip(";")
    rows = json.loads(raw)

    columns, seen = [], set()
    for row in rows:
        index = str(row.get("index", "")).strip()
        numeral, title = split_index(index)
        key = index
        if key in seen:  # a few numerals repeat with different content
            n = 2
            while f"{key} ({n})" in seen:
                n += 1
            key = f"{key} ({n})"
        seen.add(key)
        columns.append({"key": key, "numeral": numeral, "title": title})

    keys = {}
    for col_key in range(0, 35):
        values = {}
        for row, column in zip(rows, columns):
            value = clean(row.get(str(col_key)))
            if value:
                values[column["key"]] = value
        if values:
            keys[str(col_key)] = values

    # The sheet keeps the three veils on three lines of one cell. Split them
    # into the site's own keys: 000 = Ain, 00 = Ain Soph, 0 = Ain Soph Aur.
    veil = keys.get("0")
    if veil and len(str(veil.get("II. Transliteration of the Hebrew Names of the Paths", "")).split("\n")) >= 3:
        for veil_key, line in (("000", 0), ("00", 1), ("0", 2)):
            subset = {}
            for title, value in veil.items():
                parts = value.split("\n")
                subset[title] = parts[line] if len(parts) == 3 else value
            keys[veil_key] = subset

    payload = {
        "meta": {
            "title": "Liber 777",
            "subtitle": "Correspondences of Aleister Crowley",
            "source": "https://github.com/adamblvck/open_777",
            "license": "MIT (data set) / public domain (source text)",
            "credit": "Data: ADAM BLVCK — open_777. Source text: Aleister Crowley, 777 (1909).",
        },
        "columns": columns,
        "keys": keys,
    }

    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    with open(os.path.join(HERE, "liber-777.json"), "w", encoding="utf-8") as fh:
        fh.write(body)
    with open(os.path.join(HERE, "liber-777.js"), "w", encoding="utf-8") as fh:
        fh.write("/* Liber 777 data — generated by build-liber-777.py.\n"
                 " * From the open_777 data set (MIT, https://github.com/adamblvck/open_777),\n"
                 " * a transcription of Liber 777 (1909, Aleister Crowley, public domain).\n"
                 " */\n")
        fh.write("window.Liber777Data = " + body + ";\n")
    print(f"columns={len(columns)} keys={len(keys)} bytes={len(body)}")


if __name__ == "__main__":
    main()
